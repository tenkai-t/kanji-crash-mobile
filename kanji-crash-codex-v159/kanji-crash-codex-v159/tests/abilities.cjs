function contact(strike, guard, rng = () => 0, prediction = false, allies = false) {
    const world = Engine.create(); world.gravity.y = 0;
    const a = Bodies.circle(0, 0, 26, { mass: 1.5, restitution: 0.85, frictionAir: 0.025 });
    const b = Bodies.circle(53, 0, 26, { mass: 1.5, restitution: 0.85, frictionAir: 0.025 });
    a.gameData = { isPlayer: true, readingAbility: strike ? Readings.abilities.strike : null };
    b.gameData = { isPlayer: allies, readingAbility: guard ? Readings.abilities.guard : null };
    Body.setVelocity(a, { x: 8, y: 0 }); Composite.add(world.world, [a, b]);
    let pending = [], fired = [];
    Events.on(world, 'collisionStart', e => e.pairs.forEach(p => pending.push(...Skills.queueCollision(p.bodyA, p.bodyB, world.timing.timestamp, { rng, prediction }))));
    Events.on(world, 'afterUpdate', () => Skills.applyQueued(pending, (body, ability) => fired.push(ability.id)));
    Skills.onLaunch(a,0,{power:1,prediction});Engine.update(world, 1000 / 60);
    const result = { velocity: b.velocity.x, fired, wasHit: !!b.gameData.wasHitByEnemy };
    Composite.clear(world.world); Engine.clear(world); return result;
}
